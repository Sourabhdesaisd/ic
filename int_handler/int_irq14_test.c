#include "peripheral.h"

int main()
{
    info_print(0x00000);

    //------------------------------------------------------------
    // Enable Global Machine Interrupt
    // mstatus.MIE = bit 3
    //------------------------------------------------------------
    asm volatile (
        "li t0, 0x8\n"
        "csrrs x0, mstatus, t0\n"
    );

    //------------------------------------------------------------
    // Enable Machine External Interrupt
    // mie.MEIE = bit 11
    //------------------------------------------------------------
    asm volatile (
        "li t0, 0x800\n"
        "csrrs x0, mie, t0\n"
    );

    info_print(0x1111);

    //------------------------------------------------------------
    // Enable IRQ14
    //------------------------------------------------------------
    mmio_write(IRQ14_ENABLE_REG_ADDR, 0x00000001);

    //------------------------------------------------------------
    // Program IRQ14 attributes
    //------------------------------------------------------------
    mmio_write(IRQ14_ATTR_REG_ADDR, 0x00000000);

    //------------------------------------------------------------
    // Program IRQ14 control
    //------------------------------------------------------------
    mmio_write(IRQ14_CTL_REG_ADDR, 0x000000D3);

    info_print(0x2222);

    //------------------------------------------------------------
    //------------------------------------------------------------
    send_handshake_to_sv(1);

    info_print(0x3333);


}
